#!/usr/bin/env python3
"""Generate native/managed expectations from the same pinned runtime contract."""
import hashlib
import json
import re
from pathlib import Path

SOURCE = Path(__file__).resolve().parent
document = (SOURCE / 'RuntimeIdentity.json').read_bytes()
identity = json.loads(document)
assert identity['schema'] == 1 and identity['compatibilityPolicy'] >= 1
assert re.fullmatch(r'[0-9a-f]{40}', identity['everestSourceCommit'])
assert identity['builtins']['Everest'] == identity['builtins']['EverestCore']
assert set(identity['builtins']) == {'Celeste', 'CelesteIOS', 'Everest', 'EverestCore'}
assert all(re.fullmatch(r'\d+\.\d+\.\d+(\.\d+)?', v) for v in identity['builtins'].values())
digest = hashlib.sha256(document).hexdigest()
version = identity['builtins']['Everest']
version_string = version + '-cjit-' + identity['everestSourceCommit'][:7]
swift = '''// Generated by generate_runtime_identity.py from RuntimeIdentity.json.
import Foundation
enum RuntimeIdentity {
    static let manifestSHA256 = "%s"
    static let everestSourceCommit = "%s"
    static let everestVersionString = "%s"
    static let builtins: [String: String] = [%s]
    static func compatibilityFingerprint(builtins: [String: String] = builtins,
                                         pins: [String: String], policy: Int = %d) throws -> String {
        struct Policy: Encodable {
            let builtins: [String: String]
            let pins: [String: String]
            let version: Int
        }
        return digestData(try canonicalData(Policy(builtins: builtins, pins: pins, version: policy)))
    }
}
''' % (digest, identity['everestSourceCommit'], version_string,
       ', '.join(json.dumps(k) + ': ' + json.dumps(v) for k,v in sorted(identity['builtins'].items())),
       identity['compatibilityPolicy'])
managed = '''// Generated by generate_runtime_identity.py from RuntimeIdentity.json.
using System;
using System.Collections.Generic;
namespace CelesteJIT.Game;
internal static class RuntimeIdentity
{
    internal const string ManifestSHA256 = "%s";
    internal const string EverestSourceCommit = "%s";
    internal const string EverestVersionString = "%s";
    internal static Dictionary<string, Version> ExpectedModules() => new(StringComparer.Ordinal)
    {
%s
    };
}
''' % (digest, identity['everestSourceCommit'], version_string,
       '\n'.join('        { ' + json.dumps(k) + ', new Version(' + json.dumps(v) + ') },'
                 for k,v in sorted(identity['builtins'].items()) if k != 'EverestCore'))
for path, value in [(SOURCE / 'native/RuntimeIdentity.swift', swift), (SOURCE / 'managed/RuntimeIdentity.cs', managed)]:
    if not path.exists() or path.read_text() != value:
        path.write_text(value)
print('RUNTIME_IDENTITY_GENERATED', version_string, digest)
